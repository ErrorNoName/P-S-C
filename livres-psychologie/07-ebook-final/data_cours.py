def week_monday(semester, week):
    start = date.fromisoformat(ANNEE["s1_start"] if semester == 1 else ANNEE["s2_start"])
    local = week if semester == 1 else week - 15
    return start + timedelta(weeks=local - 1)


def course_iso(semester, week, kind):
    monday = week_monday(semester, week)
    day = monday + timedelta(days=0 if kind == "CM" else 3)
    clock = ANNEE["cm_time"] if kind == "CM" else ANNEE["td_time"]
    return f"{day.isoformat()}T{clock}:00"


def _slug_term(term):
    import unicodedata
    import re
    txt = unicodedata.normalize("NFD", term)
    txt = "".join(c for c in txt if unicodedata.category(c) != "Mn")
    txt = re.sub(r"[^a-zA-Z0-9]+", "-", txt).strip("-").lower()
    return txt[:60] or "notion"


def _expand_resource(key):
    if key not in _R:
        return None
    kind, rid, title, keywords = _R[key]
    href = KIND_URL[kind].format(_slug_term(rid) if kind == "glossaire" else rid)
    return {
        "key": key,
        "kind": kind,
        "id": rid,
        "title": title,
        "keywords": keywords,
        "href": href,
    }


def _phase_of(seconds):
    for phase in PHASES:
        if phase["start"] <= seconds < phase["end"] or (phase["id"] == "synthese" and seconds >= phase["start"]):
            return phase["id"]
    return "exposition"


def expand_spec(spec):
    video = VIDEOS[spec["video"]]
    resources = []
    for key in spec["resources"]:
        item = _expand_resource(key)
        if item:
            resources.append(item)

    timeline = []
    for minute, title, body, keywords, idxs in spec["beats"]:
        t = max(0, min(2999, int(minute) * 60))
        video_t = max(0, int(minute * 45))  # mapping approximatif séance → vidéo
        linked = []
        for i in idxs:
            if 0 <= i < len(resources):
                linked.append(resources[i]["key"])
        timeline.append({
            "t": t,
            "videoT": video_t,
            "phase": _phase_of(t),
            "title": title,
            "body": body,
            "keywords": keywords,
            "resources": linked,
        })

    # Garantir un marqueur au début de chaque phase.
    have = {m["phase"] for m in timeline}
    for phase in PHASES:
        if phase["id"] not in have:
            timeline.append({
                "t": phase["start"],
                "videoT": phase["start"] // 2,
                "phase": phase["id"],
                "title": phase["label"],
                "body": phase["hint"],
                "keywords": [],
                "resources": [r["key"] for r in resources[:2]],
            })
    timeline.sort(key=lambda m: m["t"])

    quiz = []
    for q, choices, correct, explain in spec["quiz"]:
        quiz.append({"q": q, "a": choices, "correct": correct, "explain": explain})

    return {
        "id": spec["id"],
        "kind": spec["kind"],
        "week": spec["week"],
        "semester": spec["semester"],
        "title": spec["title"],
        "module": spec["module"],
        "cat": spec["cat"],
        "theme": spec["theme"],
        "teacher": "Équipe pédagogique Psyclopédia",
        "guest": video["speaker"],
        "source": video["source"],
        "start": course_iso(spec["semester"], spec["week"], spec["kind"]),
        "duration": ANNEE["duration_min"],
        "video": {
            "youtube": video["youtube"],
            "title": video["title"],
            "speaker": video["speaker"],
            "source": video["source"],
            "lang": "fr",
        },
        "pages": spec["pages"],
        "resources": resources,
        "phases": PHASES,
        "timeline": timeline,
        "quiz": quiz,
    }


def get_cours():
    specs = SPECS + _more_specs()
    # Garde-fou : une seule entrée par id, 60 attendues.
    seen = {}
    for spec in specs:
        seen[spec["id"]] = spec
    ordered = sorted(seen.values(), key=lambda s: (s["semester"], s["week"], 0 if s["kind"] == "CM" else 1))
    return [expand_spec(s) for s in ordered]


def get_modules(cours=None):
    cours = cours or get_cours()
    modules = []
    seen = set()
    for c in cours:
        if c["module"] not in seen:
            seen.add(c["module"])
            modules.append(c["module"])
    return modules


def get_intervenants(cours=None):
    cours = cours or get_cours()
    names = []
    seen = set()
    for c in cours:
        guest = c["guest"]
        if guest not in seen:
            seen.add(guest)
            names.append(guest)
    return names
